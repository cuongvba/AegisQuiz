const STORAGE_KEY = 'aegisquiz-lang';
const ALT_STORAGE_KEY = 'i18nextLng';

const VALID_LANGS: LearnerLanguage[] = ['vi', 'en', 'ja', 'ko', 'ar'];

function isValidLang(val: string | null): val is LearnerLanguage {
  return val !== null && VALID_LANGS.includes(val as LearnerLanguage);
}

function resolveCurrentLang(): LearnerLanguage {
  if (typeof window === 'undefined') return 'vi';
  const queryLang = new URLSearchParams(window.location.search).get('lang');
  if (isValidLang(queryLang)) return queryLang;
  const saved = localStorage.getItem(STORAGE_KEY);
  if (isValidLang(saved)) return saved;
  const alt = localStorage.getItem(ALT_STORAGE_KEY);
  if (isValidLang(alt)) return alt;
  const legacy = localStorage.getItem('learner-app-lang');
  return isValidLang(legacy) ? legacy : 'vi';
}

export function useLearnerI18n() {
  const [lang, setLangState] = useState<LearnerLanguage>(resolveCurrentLang);

  useEffect(() => {
    // Lắng nghe sự kiện đồng bộ toàn hệ thống
    const handleSync = (e: Event) => {
      const customEvent = e as CustomEvent<LearnerLanguage>;
      if (customEvent.detail && isValidLang(customEvent.detail)) {
        setLangState(customEvent.detail);
      } else {
        setLangState(resolveCurrentLang());
      }
    };

    window.addEventListener('learner-language-changed', handleSync as EventListener);
    window.addEventListener('storage', handleSync as EventListener);

    return () => {
      window.removeEventListener('learner-language-changed', handleSync as EventListener);
      window.removeEventListener('storage', handleSync as EventListener);
    };
  }, []);

  const setLang = (nextLang: LearnerLanguage) => {
    if (!isValidLang(nextLang)) return;
    localStorage.setItem(STORAGE_KEY, nextLang);
    localStorage.setItem(ALT_STORAGE_KEY, nextLang);
    localStorage.setItem('learner-app-lang', nextLang);
    setLangState(nextLang);

    // Phát tín hiệu đồng bộ cho toàn bộ component khác trong app
    window.dispatchEvent(new CustomEvent('learner-language-changed', { detail: nextLang }));
  };

  const t = (key: string, params?: Record<string, string | number>): string => {
    let text = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
    if (params) {
      for (const [paramKey, val] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{\\{${paramKey}\\}\\}`, 'g'), String(val));
      }
    }
    return text;
  };

  return { lang, setLang, t };
}



